from main import ask, read_text

LOG = "task2"
text = read_text("text1.txt")

SYSTEM = (
    "Ти викладач фізичної терапії, який складає тести для студентів. "
    "Використовуй лише інформацію з наданого тексту, нічого не вигадуй. "
    "Відповідай українською."
)

concepts = ask(LOG, "Крок 1. Основні поняття",
    f"Випиши основні поняття (терміни) з тексту. Нумерований список, "
    f"без пояснень.\n\nТекст:\n{text}",
    system=SYSTEM)

facts = ask(LOG, "Крок 2. Ключові факти",
    f"Випиши 5-7 ключових фактів з тексту. Кожен факт одним реченням. "
    f"Нумерований список.\n\nТекст:\n{text}",
    system=SYSTEM)

questions = ask(LOG, "Крок 3. Запитання",
    f"На основі понять і фактів сформулюй 5 тестових запитань різного типу "
    f"(поняття, причина, послідовність, застосування). Тільки запитання, "
    f"без варіантів відповідей.\n\nПоняття:\n{concepts}\n\nФакти:\n{facts}",
    system=SYSTEM)

options = ask(LOG, "Крок 4. Варіанти відповідей",
    f"Для кожного запитання сформуй 4 варіанти відповіді (A-D): один "
    f"правильний і три правдоподібні, але хибні. Правильну поки не позначай."
    f"\n\nЗапитання:\n{questions}\n\nТекст для перевірки:\n{text}",
    system=SYSTEM)

final_test = ask(LOG, "Крок 5. Правильні відповіді",
    f"Для кожного запитання з варіантами визнач правильну відповідь і дай "
    f"обґрунтування одним реченням із посиланням на текст. Виведи готовий "
    f"тест у форматі: запитання, варіанти A-D, «Правильна відповідь: X», "
    f"«Обґрунтування: ...».\n\nТест:\n{options}\n\nТекст:\n{text}",
    system=SYSTEM)

single = ask(LOG, "Один загальний prompt",
    f"На основі тексту склади тест із 5 запитань. До кожного запитання дай "
    f"4 варіанти відповіді (A-D), вкажи правильну відповідь і коротке "
    f"обґрунтування.\n\nТекст:\n{text}",
    system=SYSTEM)